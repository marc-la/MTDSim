"""The 200 s ranking with the 45 s mean duration at both ends of its band.

Appendix C.1 (`app:dwell-robustness`), registry B19 (Marc 2026-10-08, threat 2
of the chapter 6 examiners; proposal P10 accepted 2026-10-09). One row per MTD
option of Table 5.3, in its order: the APT attacker model's rank at a quarter
of the 45 s mean duration, at its declared value and at four times it, then the
baseline attacker's rank, which no tactic duration moves. The last row is
Spearman's rho between the two attackers' NCR reductions at each point.

Every value is read, never typed: from
`data/results/ch5_defended/duration_ranking_numbers.json`, written by
`data/results/ch5_defended/duration_ranking.py`.

Usage:  python tools/duration_ranking_table.py
"""

from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
NUMBERS = REPO / "data" / "results" / "ch5_defended" / "duration_ranking_numbers.json"
OUT = REPO / "docs" / "thesis" / "tables" / "tab_C-1b_duration_ranking.tex"

# Grouped by layer, as Appendix D.2's tables (2026-10-14, Marc: the table has to show
# that the host layer stays above the service layer, which rank order hid).
GROUPS = (
    ("host layer", (("ip_shuffle", "IP shuffle"), ("complete_topology", "complete topology shuffle"),
                    ("host_topology", "host topology shuffle"))),
    ("service layer", (("port_shuffle", "port shuffle"), ("os_diversity", "OS diversity"),
                       ("service_diversity", "service diversity"))),
    ("credentials", (("user_shuffle", "user shuffle"),)),
    ("deployment strategies", (("random", "random"), ("mtdshield", "MTDShield"), ("alternative", "alternative"))),
)
POINTS = ("0.25", "1.0 (declared, reported corpus)", "4")


def rank(r: int) -> str:
    return r"\textbf{1}" if r == 1 else str(r)


def num(x: float) -> str:
    return f"${x:.2f}$"


def main() -> None:
    d = json.loads(NUMBERS.read_text())
    assert d["errors"] == 0, d["errors"]
    pts = [d["points"][p] for p in POINTS]
    base = d["baseline"]["rank"]
    body = []
    for k, (label, rows) in enumerate(GROUPS):
        if k:
            body.append(r"\midrule")
        body.append(r"\grouprow{5}{%s} \\" % label)
        for key, name in rows:
            body.append(r"\quad %s & " % name + " & ".join(rank(p["rank"][key]) for p in pts)
                        + f" & {rank(base[key])} \\\\")
    rho = " & ".join(f"{num(p['rho']['point'])} [{num(p['rho']['lo'])}, {num(p['rho']['hi'])}]" for p in pts)
    OUT.write_text(
        "% GENERATED by tools/duration_ranking_table.py from\n"
        "%   data/results/ch5_defended/duration_ranking_numbers.json (registry B19).\n"
        "% Do not hand-edit; regenerate. Proposal P10 (Marc 2026-10-09); regrouped by layer 2026-10-14.\n\n"
        "\\begin{table}[htbp]\n\\centering\n"
        "\\caption[The ranking at the ends of the 45\\,s mean duration's band]"
        "{The rank of each MTD mechanism and deployment strategy by NCR reduction, at a deployment "
        "interval of 200\\,s: against the APT attacker model with its 45\\,s mean duration at the low end of "
        "its band, at its declared value and at the high end, and against the baseline attacker, which uses "
        "no tactic duration (its ranks are Table~\\ref{tab:eff-cross-arm}'s). The APT attacker model "
        "averaged over $c_1$ to $c_4$, 4\\,000 runs per cell. Ranks by Scott--Knott ESD; bold: rank~1. "
        "$\\rho$: Spearman's rank correlation with the baseline attacker's NCR reductions, with its "
        "95\\,\\% interval; near 0, the two rankings are unrelated.}\n"
        "\\label{tab:duration-ranking}\n\\tablestyle\n"
        "\\begin{tabular}{@{}l *{3}{>{\\centering\\arraybackslash}p{2.6cm}} >{\\centering\\arraybackslash}p{1.8cm}@{}}\n"
        "\\toprule\n"
        "& \\multicolumn{3}{c}{APT attacker model, 45\\,s mean duration at} & \\\\\n"
        "\\cmidrule(lr){2-4}\n"
        "\\rowcolor{white}MTD & \\shortstack{11.25\\,s\\\\(low end)} & \\shortstack{45\\,s\\\\(declared)} & "
        "\\shortstack{180\\,s\\\\(high end)} & \\shortstack{Baseline\\\\attacker} \\\\\n\\midrule\n"
        + "\n".join(body) + "\n\\midrule\n"
        f"\\rowcolor{{white}}$\\rho$ with the baseline attacker & {rho} & \\\\\n"
        "\\bottomrule\n\\end{tabular}\n\\end{table}\n"
    )
    print(f"wrote {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
