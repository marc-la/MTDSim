"""The 200 s ranking with the 45 s mean duration at both ends of its band.

Appendix C.1 (`app:dwell-robustness`), registry B19 (Marc 2026-10-08, threat 2
of the chapter 6 examiners; proposal P10 accepted 2026-10-09). One row per MTD
option of Table 5.3, in its order: the APT attacker model's rank at a quarter
of the 45 s mean duration, at its declared value and at four times it, then the
baseline attacker's rank, which no tactic duration moves. The last row is
Spearman's rho between the two attackers' NCR reductions at each point.

Every value is read, never typed: from
`data/results/ch5_defended/duration_ranking_numbers.json`, written by
`data/results/ch5_defended/duration_ranking.py`.

Usage:  python tools/duration_ranking_table.py
"""

from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
NUMBERS = REPO / "data" / "results" / "ch5_defended" / "duration_ranking_numbers.json"
OUT = REPO / "docs" / "thesis" / "tables" / "tab_C-1b_duration_ranking.tex"

# Table 5.3's order and display names.
ROWS = (
    ("ip_shuffle", "IP shuffle"),
    ("host_topology", "host topology shuffle"),
    ("complete_topology", "complete topology shuffle"),
    ("random", "random"),
    ("alternative", "alternative"),
    ("service_diversity", "service diversity"),
    ("mtdshield", "MTDShield"),
    ("port_shuffle", "port shuffle"),
    ("os_diversity", "OS diversity"),
    ("user_shuffle", "user shuffle"),
)
POINTS = ("0.25", "1.0 (declared, reported corpus)", "4")


def rank(r: int) -> str:
    return r"\textbf{1}" if r == 1 else str(r)


def num(x: float) -> str:
    return f"${x:.2f}$"


def main() -> None:
    d = json.loads(NUMBERS.read_text())
    assert d["errors"] == 0, d["errors"]
    pts = [d["points"][p] for p in POINTS]
    base = d["baseline"]["rank"]
    body = [f"{name} & " + " & ".join(rank(p["rank"][key]) for p in pts) + f" & {rank(base[key])} \\\\"
            for key, name in ROWS]
    rho = " & ".join(f"{num(p['rho']['point'])} [{num(p['rho']['lo'])}, {num(p['rho']['hi'])}]" for p in pts)
    OUT.write_text(
        "% GENERATED by tools/duration_ranking_table.py from\n"
        "%   data/results/ch5_defended/duration_ranking_numbers.json (registry B19).\n"
        "% Do not hand-edit; regenerate. Proposal P10 (Marc 2026-10-09).\n\n"
        "\\begin{table}[htbp]\n\\centering\n"
        "\\caption[The ranking at the ends of the 45\\,s mean duration's band]"
        "{The MTD mechanisms and deployment strategies ranked by NCR reduction at a deployment "
        "interval of 200\\,s, with the mean duration of Persistence, Stealth and Command and Control "
        "at a quarter of its value, at its declared value and at four times its value. The APT "
        "attacker model averaged over $c_1$ to $c_4$, 4\\,000 runs per cell; the baseline attacker "
        "uses no tactic duration, so its ranks are Table~\\ref{tab:eff-cross-arm}'s. Ranks by "
        "Scott--Knott ESD; bold: rank~1. $\\rho$: Spearman's rank correlation between the two "
        "attackers' NCR reductions, with its 95\\,\\% bootstrap interval over seeds.}\n"
        "\\label{tab:duration-ranking}\n\\tablestyle\n"
        "\\begin{tabular}{@{}l *{3}{>{\\centering\\arraybackslash}p{2.3cm}} >{\\centering\\arraybackslash}p{1.8cm}@{}}\n"
        "\\toprule\n"
        "& \\multicolumn{3}{c}{APT attacker model} & Baseline attacker \\\\\n"
        "\\cmidrule(lr){2-4}\\cmidrule(lr){5-5}\n"
        "MTD & 11.25\\,s & 45\\,s & 180\\,s & \\\\\n\\midrule\n"
        + "\n".join(body) + "\n\\midrule\n"
        f"$\\rho$ & {rho} & \\\\\n"
        "\\bottomrule\n\\end{tabular}\n\\end{table}\n"
    )
    print(f"wrote {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
