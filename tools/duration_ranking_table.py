"""The 200 s ranking with the 45 s mean duration at both ends of its band.

Appendix C.1 (`app:dwell-robustness`), registry B19 (Marc 2026-10-08, threat 2
of the chapter 6 examiners; proposal P10 accepted 2026-10-09). One row per MTD
option of Table 5.3, in its order: the APT attacker model's rank at a quarter
of the 45 s mean duration, at its declared value and at four times it, then the
baseline attacker's rank, which no tactic duration moves. The last row is
Spearman's rho between the two attackers' NCR reductions at each point.

Every value is read, never typed: from
`data/results/ch5_defended/duration_ranking_numbers.json`, written by
`data/results/ch5_defended/duration_ranking.py`.

Usage:  python tools/duration_ranking_table.py
"""

from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
NUMBERS = REPO / "data" / "results" / "ch5_defended" / "duration_ranking_numbers.json"
OUT = REPO / "docs" / "thesis" / "tables" / "tab_C-1b_duration_ranking.tex"

# Grouped by layer, as Appendix D.2's tables (2026-10-14, Marc: the table has to show
# that the host layer stays above the service layer, which rank order hid).
GROUPS = (
    ("host layer", (("ip_shuffle", "IP shuffle"), ("complete_topology", "complete topology shuffle"),
                    ("host_topology", "host topology shuffle"))),
    ("service layer", (("port_shuffle", "port shuffle"), ("os_diversity", "OS diversity"),
                       ("service_diversity", "service diversity"))),
    ("credentials", (("user_shuffle", "user shuffle"),)),
    ("strategy", (("random", "random"), ("mtdshield", "MTDShield"), ("alternative", "alternative"))),
)
# Declared first, then the band's two ends (2026-10-14, Marc: order the rows by the declared
# ranking and set its column first, so the two ends are read against it).
POINTS = ("1.0 (declared, reported corpus)", "0.25", "4")


def rank(r: int) -> str:
    return r"\textbf{1}" if r == 1 else str(r)


def num(x: float) -> str:
    return f"${x:.2f}$"


def main() -> None:
    d = json.loads(NUMBERS.read_text())
    assert d["errors"] == 0, d["errors"]
    pts = [d["points"][p] for p in POINTS]
    base = d["baseline"]["rank"]
    body = []
    order = [(gi, ri, key, name, label) for gi, (label, rows) in enumerate(GROUPS) for ri, (key, name) in enumerate(rows)]
    order.sort(key=lambda r: (pts[0]["rank"][r[2]], r[0], r[1]))   # by declared rank; ties in group order
    for _, _, key, name, label in order:
        body.append(f"{name} & {label} & " + " & ".join(rank(p["rank"][key]) for p in pts)
                    + f" & {rank(base[key])} \\\\")
    # the point over its interval, the interval set smaller: two lines by design, not a wrap
    rho = " & ".join(num(p["rho"]["point"]) for p in pts)
    lo_all = min(p["rho"]["lo"] for p in pts); hi_all = max(p["rho"]["hi"] for p in pts)
    # 2026-10-14 (Marc: dedupe with the prose; "strategy" is not a layer): decode only.
    cap = (r"The rank of each MTD mechanism and deployment strategy by NCR reduction at a deployment "
           r"interval of 200\,s, with the APT attacker model's 45\,s mean duration at its declared value and "
           r"at the low and high ends of its band; the baseline attacker's ranks are Table~\ref{tab:eff-cross-arm}'s, and the APT attacker model "
           r"is averaged over $c_1$ to $c_4$. Bold: rank~1, by Scott--Knott ESD. $\rho$: "
           r"Spearman's rank correlation with the baseline attacker's NCR reductions; every 95\,\%% "
           r"interval lies within $%.2f$ and $%.2f$." % (lo_all, hi_all))
    head = (r"\rowcolor{white}MTD & Group & \shortstack{declared\\(45\,s)} & \shortstack{low end\\(11.25\,s)} & "
            r"\shortstack{high end\\(180\,s)} & \shortstack{Baseline\\attacker} \\")
    tex = "\n".join([
        "% GENERATED by tools/duration_ranking_table.py from",
        "%   data/results/ch5_defended/duration_ranking_numbers.json (registry B19).",
        "% Do not hand-edit; regenerate. Proposal P10 (Marc 2026-10-09); flat, with a Layer column, 2026-10-14.",
        "",
        r"\begin{table}[!htbp]",
        r"\centering",
        r"\caption[The ranking at the ends of the 45\,s mean duration's band]{" + cap + "}",
        r"\label{tab:duration-ranking}",
        r"\tablestyle",
        r"\begin{tabular}{@{}l l *{3}{>{\centering\arraybackslash}p{1.95cm}}>{\centering\arraybackslash}p{1.6cm}<{\hspace*{-\tabcolsep}}@{\hspace{\tabcolsep}}}",
        r"\toprule",
        r"& & \multicolumn{3}{c}{APT attacker model} & \\",
        r"\cmidrule(lr){3-5}",
        head,
        r"\midrule",
        *body,
        r"\midrule",
        r"\rowcolor{white}$\rho$ with the baseline attacker & & " + rho + r" & \\",
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
        "",
    ])
    OUT.write_text(tex)
    print(f"wrote {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
