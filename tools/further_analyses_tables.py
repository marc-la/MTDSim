"""The tables of Appendix F, Further analyses (app:further-analyses).

Registry rows B1 (+B2), B9, B10 and B14 (+B8) of the further-analyses registry
at the end of chapter 6, triaged by Marc 2026-10-09 (handoff
2026-10-09_ch7_conclusion_and_appendix_structure sections 8-9). Every value is
read, never typed: from
`data/results/ch6_further_analyses/further_analyses_numbers.json`, written by
`data/results/ch6_further_analyses/further_analyses.py`. A section whose numbers
are not yet written is skipped.

Shares print with their 95 % Clopper--Pearson interval (results presentation
standard N4); means with a 95 % percentile bootstrap interval over runs, as
chapter 5 prints them.

Usage:  python tools/further_analyses_tables.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _ch5_style import IV_BOOT, IV_PROP, LONG, REPO, TAB_DIR, bounded, clopper_pearson  # noqa: E402

NUMBERS = REPO / "data" / "results" / "ch6_further_analyses" / "further_analyses_numbers.json"
HEAD = ("% GENERATED by tools/further_analyses_tables.py from\n"
        "%   data/results/ch6_further_analyses/further_analyses_numbers.json ({rows}).\n"
        "% Do not hand-edit; regenerate. Appendix F (Marc 2026-10-09).\n\n")
CODES = ("c1", "c2", "c3", "c4")
PROFILE_OF = dict(zip(CODES, ("objective_exfiltration", "objective_impact",
                              "objective_exfiltration_impact", "objective_none_c2")))
INTERVALS = (50, 100, 200, 500, 1000, 2000)


def th(n: int) -> str:
    """A count with the house thousands space (1\\,000)."""
    return f"{n:,}".replace(",", "\\,")


def f(x: float, nd: int = 2) -> str:
    return bounded(x, nd, lo=0.0, hi=1.0)


def share(p: float, n: int, nd: int = 2) -> str:
    k = round(p * n)
    lo, hi = clopper_pearson(k, n)
    return f"{f(p, nd)} [{f(lo, nd)}, {f(hi, nd)}]"


def mean_iv(d: dict, nd: int = 2) -> str:
    return f"${d['mean']:.{nd}f}$ [{d['lo']:.{nd}f}, {d['hi']:.{nd}f}]"


def write(stem: str, rows: str, body: str) -> None:
    out = TAB_DIR / f"{stem}.tex"
    out.write_text(HEAD.format(rows=rows) + body)
    print(f"wrote {out.relative_to(REPO)}")


def t_success(d: dict) -> None:
    n = d["n_seeds"]
    nb = d["baseline_successes"]
    rows = []
    for c in CODES:
        p = d["profiles"][c]
        rows.append(f"$c_{c[1]}$ & {p['successes']} & {f(p['asp'])} & {p['successes_where_baseline_succeeds']} & "
                    f"{f(p['asp_where_baseline_succeeds'])} & {p['successes_where_baseline_fails']} & "
                    f"{f(p['asp_where_baseline_fails'])} \\\\")
    write("tab_FA-1a_success_by_seed", "registry B1", (
        "\\begin{table}[htbp]\n\\centering\n"
        "\\caption[Each attack profile's successes, split by the baseline attacker's]"
        f"{{Each attack profile's runs that compromise a target host with no MTD, on the {th(n)} seeds of "
        "Table~\\ref{tab:unopposed-summary}, split by whether the baseline attacker compromises a target "
        f"host on the same seed ({nb} seeds) or not ({n - nb}). Both attackers run on the network each seed "
        "generates. Success is Table~\\ref{tab:unopposed-summary}'s rule.}\n"
        + "\\label{tab:fa-success}\n\\tablestyle\n"
        "\\begin{tabular}{@{}l *{6}{c}@{}}\n\\toprule\n"
        f"& \\multicolumn{{2}}{{c}}{{All {th(n)} seeds}} & \\multicolumn{{2}}{{c}}{{Baseline attacker succeeds}} "
        "& \\multicolumn{2}{c}{Baseline attacker fails} \\\\\n"
        + "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}\n"
        "Attack profile & Runs & ASP & Runs & ASP & Runs & ASP \\\\\n\\midrule\n"
        + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n"))
    pr = []
    for key, v in d["pairs"].items():
        a, b = key.split("-")
        pr.append(f"$c_{a[1]}$ and $c_{b[1]}$ & {v['both']} & ${v['expected']:.1f}$ & ${v['ratio']:.1f}$ \\\\")
    write("tab_FA-1b_success_pairs", "registry B1", (
        "\\begin{table}[htbp]\n\\centering\n"
        "\\caption[Seeds on which two attack profiles both succeed]"
        "{The seeds on which two attack profiles both compromise a target host with no MTD, against the "
        "number expected if their successes were independent of the seed (the product of their successes "
        f"over {th(n)} seeds), and the ratio of the two.}}\n"
        + "\\label{tab:fa-success-pairs}\n\\tablestyle\n"
        "\\begin{tabular}{@{}l *{3}{c}@{}}\n\\toprule\n"
        "Attack profiles & Seeds, both succeed & Expected & Ratio \\\\\n\\midrule\n"
        + "\n".join(pr) + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n"))


def t_foothold(d: dict) -> None:
    c = d["conditions"]
    lines = []
    none = c["none|0"]
    lines.append(f"no MTD & & {share(none['apt']['mean'], none['apt']['n'])} & "
                 f"{share(none['baseline']['mean'], none['baseline']['n'])} \\\\")
    for mech in ("ip_shuffle", "host_topology", "complete_topology"):
        lines.append("\\midrule")
        for i, iv in enumerate(INTERVALS):
            x = c[f"{mech}|{iv}"]
            name = LONG[mech] if i == 0 else ""
            lines.append(f"{name} & {th(iv)} & {share(x['apt']['mean'], x['apt']['n'])} & "
                         f"{share(x['baseline']['mean'], x['baseline']['n'])} \\\\")
    write("tab_FA-2_foothold", "registry B9", (
        "\\begin{table}[htbp]\n\\centering\n"
        "\\caption[The share of runs that compromise no host, under the host layer]"
        "{The share of each attacker's runs that compromise no host by the 15\\,000\\,s time limit, with no "
        "MTD and under each host-layer MTD mechanism at every deployment interval: the APT attacker model "
        "averaged over $c_1$ to $c_4$ (4\\,000 runs per row) and the baseline attacker (1\\,000 runs per row), "
        f"each with its {IV_PROP}.}}\n"
        "\\label{tab:fa-foothold}\n\\tablestyle\n"
        "\\begin{tabular}{@{}l r c c@{}}\n\\toprule\n"
        "MTD & Deployment interval (s) & APT attacker model & Baseline attacker \\\\\n\\midrule\n"
        + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n"))


def t_accounts(d: dict) -> None:
    c = d["cells"]
    rows = []
    for cond, iv, name in [("none", 0, "no MTD", )] + [("user_shuffle", iv, f"user shuffle, {th(iv)}\\,s")
                                                       for iv in INTERVALS]:
        a, b = c[f"apt|{cond}|{iv}"], c[f"baseline|{cond}|{iv}"]
        rows.append(f"{name} & {mean_iv(a['reuse_per_run'])} & {mean_iv(a['hosts_per_run'])} & "
                    f"{mean_iv(b['reuse_per_run'])} & {mean_iv(b['hosts_per_run'])} \\\\")
        if cond == "none":
            rows.append("\\midrule")
    write("tab_FA-3_accounts", "registry B10", (
        "\\begin{table}[htbp]\n\\centering\n"
        "\\caption[Hosts compromised by a held account, with no MTD and under user shuffle]"
        "{Hosts each attacker compromises per run by logging in with an account it already holds, a port "
        "scan that compromises the host, and all hosts it compromises per run, with no MTD and under user "
        "shuffle at every deployment interval: the APT attacker model averaged over $c_1$ to $c_4$ (4\\,000 "
        f"runs per row) and the baseline attacker (1\\,000 runs per row). Brackets: {IV_BOOT}.}}\n"
        "\\label{tab:fa-accounts}\n\\tablestyle\n"
        "\\begin{tabular}{@{}l *{4}{c}@{}}\n\\toprule\n"
        "& \\multicolumn{2}{c}{APT attacker model} & \\multicolumn{2}{c}{Baseline attacker} \\\\\n"
        "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\n"
        "MTD & By a held account & All & By a held account & All \\\\\n\\midrule\n"
        + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n"))


def t_group_size(d: dict) -> None:
    sizes = d.get("slot_sizes") or {}
    rows = []
    for c in CODES:
        s = d["slots"][c]
        size = sizes.get(PROFILE_OF[c]) if isinstance(sizes, dict) else None
        rn, ra = s["random_ncr"], s["random_asp"]
        k = len(rn["values"])
        rows.append(f"$c_{c[1]}$ & {size if size is not None else ''} & {f(s['profile_ncr'])} & "
                    f"{f(rn['median'])} [{f(rn['min'])}, {f(rn['max'])}] & "
                    f"{s['random_groups_below_profile_ncr']} of {k} & {f(s['profile_asp'])} & "
                    f"{f(ra['median'])} [{f(ra['min'])}, {f(ra['max'])}] \\\\")
    write("tab_FA-5_group_size", "registry B14, B8", (
        "\\begin{table}[htbp]\n\\centering\n"
        "\\caption[Each attack profile against random groups of the same size]"
        "{NCR and ASP with no MTD of each attack profile and of the random groups of attack flows of the "
        "same size, one group per random partition of Table~\\ref{tab:ablation-random-partitions}: the "
        "median over the ten groups, with their minimum and maximum in brackets, and how many of the ten "
        f"have a lower NCR than the attack profile. {th(d['n_seeds'])} seeds per group. The attack graph of "
        f"all 38 attack flows has an NCR of {d['aggregate_ncr']:.2f}.}}\n"
        + "\\label{tab:fa-group-size}\n\\tablestyle\n"
        "\\begin{tabular}{@{}l c c c c c c@{}}\n\\toprule\n"
        "& & \\multicolumn{3}{c}{NCR} & \\multicolumn{2}{c}{ASP} \\\\\n"
        "\\cmidrule(lr){3-5}\\cmidrule(lr){6-7}\n"
        "Attack profile & Attack flows & Profile & Random groups & Below profile & Profile & Random groups \\\\\n"
        "\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n"))


def main() -> None:
    d = json.loads(NUMBERS.read_text())
    for key, fn in (("f1", t_success), ("f2", t_foothold), ("f3", t_accounts), ("f5", t_group_size)):
        if key in d:
            fn(d[key])
        else:
            print(f"skip {key}: no numbers yet")


if __name__ == "__main__":
    main()
