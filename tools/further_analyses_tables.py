def t_after_foothold(d: dict) -> None:
    verbs = ("SCAN_HOST", "ENUM_HOST", "SCAN_PORT", "EXPLOIT_VULN", "BRUTE_FORCE", "SCAN_NEIGHBOR")
    br = "\\\\"
    head = " & ".join("\\shortstack{" + ACTIVITY[v].capitalize().replace(" ", br) + "}" for v in verbs)
    rows = []
    for who, label in [(c, f"$c_{c[1]}$") for c in CODES] + [("baseline", "Baseline attacker")]:
        if who == "baseline":
            rows.append("\\midrule")
        x = d[who]
        cells = " & ".join(f"{100 * x['after_foothold_share'][v]:.1f}" for v in verbs)
        rows.append(f"{label} & {th(x['runs_with_foothold'])} & {cells} \\\\")
    write("tab_FA-6b_after_foothold", "registry A3", (
        "\\begin{table}[htbp]\n\\centering\n"
        "\\caption[Each attack action's share after the foothold]"
        "{Each attack action's share of an attacker's attack actions after the foothold, its first "
        "compromise of a host, with no MTD, in percent, pooled over the runs that gain a foothold. "
        "Attack actions counted as Table~\\ref{tab:unopposed-summary} counts them. A printed 0.0 is exact.}\n"
        "\\label{tab:fa-after-foothold}\n\\tablestyle\\setlength{\\tabcolsep}{4pt}\n"
        "\\begin{tabular}{@{}l c c c c c c c@{}}\n\\toprule\n"
        f"Attacker & \\shortstack{{Runs with\\\\a foothold}} & {head} \\\\\n"
        "\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n"))


def pm(x: dict, nd: int, scale: float = 1.0) -> str:
    half = max(x["mean"] - x["lo"], x["hi"] - x["mean"]) * scale
    return f"${x['mean'] * scale:.{nd}f} \\pm {half:.{nd}f}$"


