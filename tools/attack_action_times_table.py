"""Each attack action's time in MTDSim beside the tactic durations that drive it.

Appendix B (`app:dwell-derivation`), registry B21 (Marc 2026-10-08, threat 9 of
the chapter 6 examiners: the two attackers do not run under identical
conditions, because the APT attacker model's attack actions take the duration
of the tactic that dispatches them, not MTDSim's time). One row per MTDSim
attack action, in the order Section 2.2.3 gives them: MTDSim's time, then each
tactic the mapping sends to it with that tactic's mean duration. The unmapped
tactics close the table, since they take time and dispatch nothing.

Every value is read, never typed (`figure_table_conventions.md` §h): MTDSim's
times from `mtdnetwork/data/constants.py`, the mapping from
`data/ogasp/controller/mappings/v2_partial.csv`, the durations from
`data/ogasp/tactic_durations.json`, the display names from the pinned ATT&CK
bundle through `_tactic_axis`.

Usage:  python tools/attack_action_times_table.py
"""

from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _tactic_axis import load_axis  # noqa: E402

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))
from mtdnetwork.data import constants  # noqa: E402  MTDSim's attack-action costs

CATALOGUE = REPO / "data" / "ogasp" / "tactic_durations.json"
MAPPING = REPO / "data" / "ogasp" / "controller" / "mappings" / "v2_partial.csv"
OUT = REPO / "docs" / "thesis" / "tables" / "tab_B-4b_attack_action_times.tex"

# Display names as Section 2.2.3 and Table B.5 name the attack actions.
ACTIONS = {
    "SCAN_HOST": "scan host",
    "ENUM_HOST": "enumerate host",
    "SCAN_NEIGHBOR": "scan neighbours",
    "SCAN_PORT": "scan port",
    "EXPLOIT_VULN": "exploit",
    "BRUTE_FORCE": "brute force",
}


def fmt(x: float) -> str:
    return f"{x:g}" if float(x).is_integer() else f"{x:.1f}"


def main() -> None:
    cat = json.loads(CATALOGUE.read_text())["tactics"]
    axis = load_axis()
    axis.check_against(list(cat))
    with MAPPING.open() as fh:
        mapping = {r["tactic"]: r["sim_phase"] for r in csv.DictReader(fh)}

    cost = constants.ATTACK_DURATION
    lo = cost["EXPLOIT_VULN"] * (1 - 1.0)
    hi = cost["EXPLOIT_VULN"] * (1 - constants.VULN_MIN_COMPLEXITY)
    mid = cost["EXPLOIT_VULN"] * (1 - (constants.VULN_MIN_COMPLEXITY + 1) / 2)

    def mtdsim_time(action: str) -> str:
        if action == "EXPLOIT_VULN":  # per vulnerability: 15 x (1 - complexity)
            return f"{fmt(lo)} to {fmt(hi)} (mean {fmt(mid)})"
        return fmt(cost[action])

    def tactics_of(action: str | None) -> list[str]:
        return [t for t in axis.matrix_order if (mapping[t] or None) == action]

    # 2026-10-14 (Marc: "looks tacky"): one row per tactic in ATT&CK's order, the
    # attack action it runs and the two times side by side; no group rules. An
    # unmapped tactic runs no attack action: its action and MTDSim time are blank
    # (not applicable, results_presentation_standard.md S).
    rev = {}
    for a in ACTIONS:
        for t in tactics_of(a):
            rev[t] = a
    lines, rows = [], []
    for t in axis.matrix_order:
        a = rev.get(t)
        act, time = (ACTIONS[a], fmt(mid) if a == "EXPLOIT_VULN" else mtdsim_time(a)) if a else (r"\emph{unmapped}", "")
        lines.append(f"{axis.label[t]} & {act} & {time} & {fmt(cat[t]['duration_s'])} \\\\")
        rows.append((axis.label[t], act, time, fmt(cat[t]['duration_s'])))
    body = "\n".join(lines)
    OUT.write_text(
        "% GENERATED by tools/attack_action_times_table.py from\n"
        "%   mtdnetwork/data/constants.py, data/ogasp/controller/mappings/v2_partial.csv\n"
        f"%   and data/ogasp/tactic_durations.json; display names from the pinned ATT&CK bundle (v{axis.version}).\n"
        "% Do not hand-edit; regenerate. Registry B21 (Marc 2026-10-08); one row per tactic, ATT&CK order, 2026-10-14.\n\n"
        "\\begin{table}[htbp]\n\\centering\n"
        "\\caption[The baseline attacker's times and the tactic durations]"
        "{Each tactic, in ATT\\&CK's order, with the attack action it runs (Figure~\\ref{fig:controller-mapping}), "
        "that attack action's time in MTDSim, which the baseline attacker takes, and the tactic's mean duration, "
        "which the APT attacker model takes instead. The exploit's time is its mean: it runs "
        f"{fmt(lo)} to {fmt(hi)}\\,s, by the vulnerability. An unmapped tactic runs no attack action.}}\n"
        "\\label{tab:attack-action-times}\n\\tablestyle\n"
        "\\begin{tabular}{@{}l l r r@{}}\n\\toprule\n"
        "Tactic & Attack action & MTDSim's time (s) & Mean duration (s) \\\\\n\\midrule\n"
        f"{body}\n\\bottomrule\n\\end{{tabular}}\n\\end{{table}}\n"
    )
    print(f"wrote {OUT.relative_to(REPO)}")
    for r in rows:
        print("  ", " | ".join(r))


if __name__ == "__main__":
    main()
